"""Gemini API Client for AUTOSAR HLD Document Analysis.

Provides secure client initialization via environment variables,
graceful error handling for missing keys, quota limits, and network issues,
and grounded prompt dispatch with mockability for test suites.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from typing import Any, Dict, List, Optional

from dotenv import load_dotenv

# Load environment variables from .env if present
load_dotenv()

try:
    from google import genai
    from google.genai import types
    from google.genai.errors import APIError, ClientError
except ImportError:
    genai = None
    types = None
    APIError = Exception
    ClientError = Exception


class LLMError(Exception):
    """Base exception for LLM operations."""
    pass


class LLMConfigurationError(LLMError):
    """Raised when the API key or required client configuration is missing."""
    pass


class LLMQuotaExceededError(LLMError):
    """Raised when API rate limit or quota has been reached."""
    pass


class LLMNetworkError(LLMError):
    """Raised when communication with the LLM API fails due to network/connectivity issues."""
    pass


class LLMResponseError(LLMError):
    """Raised when the LLM returns an invalid, empty, or blocked response."""
    pass


@dataclass
class GroundedResponse:
    """Encapsulates the grounded response generated by the LLM."""
    content: str
    model_name: str
    is_successful: bool = True
    error_message: Optional[str] = None


class GeminiClient:
    """Client for Google's Gemini API with grounding enforcement and safe error handling."""

    DEFAULT_MODEL = "gemini-2.5-flash"

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
        client_instance: Optional[Any] = None,
    ) -> None:
        """Initializes the Gemini client.

        Args:
            api_key: Optional API key. If omitted, fetched from GEMINI_API_KEY env var.
            model: Model name to use (defaults to gemini-2.5-flash).
            client_instance: Optional pre-configured or mocked client instance for testing.
        """
        self.model = model or os.getenv("GEMINI_MODEL", self.DEFAULT_MODEL)

        if client_instance is not None:
            self._client = client_instance
            return

        resolved_key = api_key or os.getenv("GEMINI_API_KEY")
        if not resolved_key or not resolved_key.strip():
            raise LLMConfigurationError(
                "Gemini API key is not configured. Please set the GEMINI_API_KEY environment variable "
                "in a '.env' file or provide it via the dashboard sidebar."
            )

        if genai is None:
            raise LLMConfigurationError(
                "The 'google-genai' package is not installed. Please install it using 'pip install google-genai'."
            )

        try:
            self._client = genai.Client(api_key=resolved_key.strip())
        except Exception as e:
            raise LLMConfigurationError(f"Failed to initialize Gemini Client: {str(e)}") from e

    @staticmethod
    def is_api_key_configured(override_key: Optional[str] = None) -> bool:
        """Checks if a valid API key is present in environment or override."""
        key = override_key or os.getenv("GEMINI_API_KEY")
        return bool(key and key.strip())

    def generate_grounded_response(
        self,
        user_query: str,
        doc_overview: Dict[str, Any],
        extraction_result: Any,
        chat_history: Optional[List[Dict[str, str]]] = None,
        temperature: float = 0.2,
    ) -> GroundedResponse:
        """Sends a grounded AUTOSAR prompt to the Gemini API and returns the structured answer."""
        from .prompts import AUTOSARPromptBuilder

        if not user_query or not user_query.strip():
            return GroundedResponse(
                content="Please provide a valid question regarding the AUTOSAR HLD document.",
                model_name=self.model,
                is_successful=False,
                error_message="Empty query provided.",
            )

        prompt = AUTOSARPromptBuilder.build_grounded_prompt(
            user_query=user_query,
            doc_overview=doc_overview,
            extraction_result=extraction_result,
            chat_history=chat_history,
        )

        try:
            # Build config if types module is available
            config_params = {}
            if types and hasattr(types, "GenerateContentConfig"):
                config_params["config"] = types.GenerateContentConfig(
                    system_instruction=AUTOSARPromptBuilder.SYSTEM_INSTRUCTION,
                    temperature=temperature,
                )

            response = self._client.models.generate_content(
                model=self.model,
                contents=prompt,
                **config_params,
            )

            response_text = getattr(response, "text", "")
            if not response_text:
                raise LLMResponseError(
                    "The model returned an empty response. This may occur if the content triggered safety filters."
                )

            return GroundedResponse(
                content=response_text,
                model_name=self.model,
                is_successful=True,
            )

        except ClientError as e:
            err_str = str(e)
            code = getattr(e, "code", None)
            if code == 429 or "429" in err_str or "RESOURCE_EXHAUSTED" in err_str or "quota" in err_str.lower():
                raise LLMQuotaExceededError(
                    f"Gemini API quota exceeded or rate limit reached (Code {code}): {err_str}"
                ) from e
            raise LLMResponseError(f"Gemini API client error (Code {code}): {err_str}") from e

        except APIError as e:
            err_str = str(e)
            code = getattr(e, "code", None)
            if code == 429 or "429" in err_str or "quota" in err_str.lower():
                raise LLMQuotaExceededError(
                    f"Gemini API quota exceeded (Code {code}): {err_str}"
                ) from e
            raise LLMResponseError(f"Gemini API error (Code {code}): {err_str}") from e

        except Exception as e:
            # Check for network or connection issues
            err_name = type(e).__name__
            err_msg = str(e).lower()
            if any(term in err_msg for term in ["connection", "timeout", "unreachable", "socket", "network"]):
                raise LLMNetworkError(f"Network error while communicating with Gemini API: {str(e)}") from e
            if isinstance(e, (LLMConfigurationError, LLMQuotaExceededError, LLMNetworkError, LLMResponseError)):
                raise
            raise LLMResponseError(f"Unexpected error during LLM generation ({err_name}): {str(e)}") from e
